def _load_questions() -> dict[str, dict]:
    """讀取並套用指定的中文選項修正，只保留 L001–L050。"""
    questions = json.loads(_QUESTION_FILE.read_text(encoding="utf-8"))
    selected = {question["id"]: question for question in questions if question["id"] in _IDS}
    if set(selected) != set(_IDS):
        missing = sorted(set(_IDS) - set(selected))
        raise ValueError(f"questions3.json 缺少題目：{missing}")

    for question_id, fixes in CHOICE_ZH_FIX.items():
        choices = {choice["key"]: choice for choice in selected[question_id]["choices"]}
        for key, text in fixes.items():
            choices[key]["zh"] = text
    return selected


def _sentences(text: str, limit: int = 5) -> list[str]:
    parts = [part.strip() for part in re.findall(r"[^。！？]+[。！？]", text) if part.strip()]
    if not parts and text.strip():
        parts = [text.strip().rstrip("。") + "。"]
    return parts[:limit]


def _bullet_lines(text: str) -> list[str]:
    return [line.strip() for line in text.splitlines() if line.strip().startswith("• ")]


def _core_zh(explanation: str) -> str:
    text = (explanation or "").strip()
    text = re.split(r"\nEnglish[：:]", text, maxsplit=1)[0].strip()
    text = re.sub(r"^正確選項\s*\([A-D]\)\s*(?:深度)?解析[：:]\s*", "", text).strip()
    for marker in ("【再講清楚一點】", "【干擾選項拆解", "【考試陷阱】", "【延伸考點"):
        if marker in text:
            text = text.split(marker, 1)[0].strip()
    text = re.sub(r"\n考試陷阱[^\n]*", "", text).strip()
    return text


def _build_pack() -> dict[str, dict]:
    questions = _load_questions()
    pack: dict[str, dict] = {}
    for question_id in _IDS:
        question = questions[question_id]
        choices = {choice["key"]: choice for choice in question["choices"]}
        answer = question["answer"]
        wrong_keys = [key for key in ("A", "B", "C", "D") if key in choices and key != answer]
        if set(_WRONG_CORE[question_id]) != set(wrong_keys):
            raise ValueError(f"{question_id} 的 wrong 鍵與非答案選項不一致")
        wrong = {key: _WRONG_CORE[question_id][key] for key in wrong_keys}
        answer_zh = (choices[answer].get("zh") or choices[answer]["en"]).strip().rstrip("。！？")
        why = (
            f"本題關鍵鎖定「{answer_zh}」：先判斷題幹在問定義、法律效果、時點還是計算層級，再逐一核對選項是否缺要件。"
            f"干擾項常把相近術語錯層級並列；用「誰／何時／何義務／何例外」四問快速排除。"
            f"特別留意：({wrong_keys[0]}) {choices[wrong_keys[0]].get('zh') or choices[wrong_keys[0]]['en']}；"
            f"({wrong_keys[1]}) {choices[wrong_keys[1]].get('zh') or choices[wrong_keys[1]]['en']}；"
            f"({wrong_keys[2]}) {choices[wrong_keys[2]].get('zh') or choices[wrong_keys[2]]['en']}。"
        )
        traps = [
            "• 先看題幹動詞：問的是『定義／例外／優先順位／計算步驟』哪一層，不要被故事情節帶走。",
            "• 出現兩個相近專有名詞時，先對照差異表（例如仲裁 vs 調解、專任 vs 獨家代理、EGI vs NOI）。",
        ]
        traps += [
            f"• 選項 {key}「{choices[key].get('zh') or choices[key]['en']}」陷阱：{_WRONG_CORE[question_id][key]}"
            for key in wrong_keys
        ]
        extend = [
            f"• 正確答案對照：({answer}) {choices[answer]['en']}＝{choices[answer].get('zh') or ''}"
        ]
        extend += [
            f"• 易混對照：({key}) {choices[key]['en']}＝{choices[key].get('zh') or ''}｜{_WRONG_CORE[question_id][key]}"
            for key in wrong_keys
        ]
        extend.append("• 記憶口訣：同一主題連續出題時，畫『正確要件／常見例外／禁止事項』三欄最有效。")
        pack[question_id] = {
            "why": why,
            "traps": "\n".join(traps[:6]),
            "extend": "\n".join(extend[:6]),
            "wrong": wrong,
        }
    return pack


PACK = _build_pack()


def _validate() -> None:
    questions = _load_questions()
    assert len(PACK) == 50
    assert set(PACK) == set(_IDS)
    for question_id, item in PACK.items():
        question = questions[question_id]
        wrong_keys = {choice["key"] for choice in question["choices"]} - {question["answer"]}
        assert set(item["wrong"]) == wrong_keys
        assert len(_bullet_lines(item["traps"])) >= 4
        assert len(_bullet_lines(item["extend"])) >= 4
    l036_choices = {choice["key"]: choice["en"] for choice in questions["L036"]["choices"]}
    assert l036_choices["B"] == "electromagnetic"
    assert l036_choices["C"] == "asbestosis"
    assert l036_choices["D"] == "radioactive"
    wrong_b = PACK["L036"]["wrong"]["B"]
    wrong_c = PACK["L036"]["wrong"]["C"]
    wrong_d = PACK["L036"]["wrong"]["D"]
    assert "電磁" in wrong_b or "electromagnetic" in wrong_b.lower()
    assert "asbestosis" in wrong_c.lower() or "疾病" in wrong_c or "沉著" in wrong_c
    assert "放射" in wrong_d


